# EXAMPLE 3:

X = int(input("Enter FIRST number: "))
Y = int(input("Enter SECOND number: "))
print(X + Y)  # Output: The sum of the two numbers entered by the user
print(int(X) + int(Y))  # This line is redundant since X and Y are already integers, but it demonstrates typecasting.



# Example 4: Taking user input for a string
name = input("Enter your name: ")
print("Hello, " + name + "!")

# Example 5: Taking user input for an integer
age = int(input("Enter your age: "))
print("You are " + str(age) + " years old.")

# Example 6: Taking user input for a float
price = float(input("Enter the price: "))
print("The price is $" + str(price))






