# MORE EXAMPLES OF STRINGS IN PYTHON

# EXAMPLE 1:
NAME = "KRITIKA"

print(NAME[0])  # Output: K (character at index 0)
print(NAME[1])  # Output: R (character at index 1)
print(NAME[2])  # Output: I (character at index 2)
print(NAME[3])  # Output: T (character at index 3)
print(NAME[4])  # Output: I (character at index 4)
print(NAME[5])  # Output: K (character at index 5)
print(NAME[6])   # Output: A (character at index 6)
# print(NAME[7])  # Output: IndexError: string index out of range (since the string has only 7 characters)
print(NAME) # Output: KRITIKA (the entire string)


print(NAME[-1])  # Output: A (last character)
print(NAME[-2])  # Output: K (second last character)
print(NAME[-3])  # Output: I (third last character)
print(NAME[-4])  # Output: T (fourth last character)
print(NAME[-5])  # Output: I (fifth last character)
print(NAME[-6])  # Output: R (sixth last character)
# print(NAME[-7])  # Output: K (seventh last character)



