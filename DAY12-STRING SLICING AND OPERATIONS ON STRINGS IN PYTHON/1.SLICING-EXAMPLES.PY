# EXAMPLE OF SLICING IN PYTHON

# 1). EXAMPLE OF SLICING IN PYTHON

NAME = "KRITIKA"

print(NAME[:])  # OUTPUT: KRITIKA
print(NAME[0:])  # OUTPUT: KRITIKA
print(NAME[:7])  # OUTPUT: KRITIKA
print(NAME[0:7])  # OUTPUT: KRITIKA

print(NAME[0:1])  #OUTPUT:K
print(NAME[0:2])  #OUTPUT:KR
print(NAME[0:3])  #OUTPUT:KRI
print(NAME[0:4])  #OUTPUT:KRIT
print(NAME[0:5])  #OUTPUT:KRITI
print(NAME[0:6])  #OUTPUT:KRITIK
print(NAME[0:7])  #OUTPUT:KRITIKA

